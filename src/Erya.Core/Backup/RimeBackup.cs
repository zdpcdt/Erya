using System.IO.Compression;

namespace Erya.Core.Backup;

/// <summary>Outcome summary of one backup or restore run.</summary>
/// <param name="FileCount">Files actually packed / restored (skipped ones excluded).</param>
/// <param name="Bytes">Uncompressed bytes processed.</param>
/// <param name="SkippedFiles">Entries left out, each with the reason.</param>
/// <param name="SafetyBackupPath">Restore only: snapshot of the pre-restore state.</param>
public sealed record RimeBackupReport(
    int FileCount,
    long Bytes,
    IReadOnlyList<string> SkippedFiles,
    string? SafetyBackupPath = null)
{
    public bool HasSkippedFiles => SkippedFiles.Count > 0;
}

/// <summary>
/// Packs the RIME user directory into a zip archive and restores one back,
/// overwriting the current contents.
/// <para>
/// Safety rules: the derived <c>build/</c> folder (regenerated by every deploy)
/// never enters an archive; a restore first snapshots the current user
/// directory into a <c>pre-restore-*.zip</c> next to the chosen backup, so a
/// bad restore can always be rolled back by restoring that snapshot; entries
/// escaping the target directory (zip slip) are skipped, never written.
/// </para>
/// <para>
/// Files locked by a running frontend (logs, open user dictionaries) are
/// skipped and reported instead of failing the whole run — RIME does not
/// require them for configuration purposes.
/// </para>
/// </summary>
public static class RimeBackup
{
    /// <summary>Deployed schema binaries; regenerated on every deploy.</summary>
    public const string ExcludedDirName = "build";

    public static RimeBackupReport Create(string userDir, string targetZipPath, CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrEmpty(userDir);
        ArgumentException.ThrowIfNullOrEmpty(targetZipPath);
        if (!Directory.Exists(userDir))
            throw new DirectoryNotFoundException($"用户目录不存在：{userDir}");

        targetZipPath = Path.GetFullPath(targetZipPath);
        Directory.CreateDirectory(Path.GetDirectoryName(targetZipPath)!);

        var userRoot = Path.TrimEndingDirectorySeparator(Path.GetFullPath(userDir));
        var skipped = new List<string>();
        long bytes = 0;
        int packed = 0;

        using (var stream = File.Create(targetZipPath))
        using (var archive = new ZipArchive(stream, ZipArchiveMode.Create))
        {
            foreach (var file in EnumerateUserFiles(userRoot))
            {
                cancellationToken.ThrowIfCancellationRequested();
                try
                {
                    // ReadWrite share: Weasel keeps logs/dictionaries open while running.
                    using var input = new FileStream(file, FileMode.Open, FileAccess.Read,
                        FileShare.ReadWrite | FileShare.Delete);
                    var entry = archive.CreateEntry(RelativeName(userRoot, file), CompressionLevel.Optimal);
                    using var output = entry.Open();
                    input.CopyTo(output);
                    packed++;
                    bytes += input.Length;
                }
                catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
                {
                    skipped.Add($"{RelativeName(userRoot, file)}（{ex.Message}）");
                }
            }
        }

        return new RimeBackupReport(packed, bytes, skipped);
    }

    public static RimeBackupReport Restore(string zipPath, string userDir, CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrEmpty(zipPath);
        ArgumentException.ThrowIfNullOrEmpty(userDir);
        if (!File.Exists(zipPath))
            throw new FileNotFoundException($"找不到备份文件：{zipPath}");

        var root = Path.TrimEndingDirectorySeparator(Path.GetFullPath(userDir));
        Directory.CreateDirectory(root);

        using var stream = File.OpenRead(zipPath);
        using var archive = new ZipArchive(stream, ZipArchiveMode.Read);
        if (archive.Entries.Count == 0)
            throw new InvalidDataException("该压缩包不含任何文件，不是有效的 RIME 备份。");

        // Snapshot before touching anything — this is the rollback path.
        string? safetyPath = null;
        if (DirectoryHasFiles(root))
        {
            safetyPath = SafetyBackupZipPath(zipPath);
            try
            {
                Create(root, safetyPath, cancellationToken);
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                throw new InvalidOperationException(
                    $"无法在备份所在目录生成安全备份（{safetyPath}），已中止恢复。可先将备份复制到可写目录再试。", ex);
            }
        }

        var skipped = new List<string>();
        long bytes = 0;
        int restored = 0;

        foreach (var entry in archive.Entries)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var targetPath = SafeResolve(root, entry.FullName);
            if (targetPath is null)
            {
                skipped.Add($"{entry.FullName}（路径越出用户目录，已跳过）");
                continue;
            }

            if (string.IsNullOrEmpty(entry.Name)) continue; // bare directory entry

            try
            {
                Directory.CreateDirectory(Path.GetDirectoryName(targetPath)!);
                using var input = entry.Open();
                using var output = new FileStream(targetPath, FileMode.Create, FileAccess.Write,
                    FileShare.Read);
                input.CopyTo(output);
                restored++;
                bytes += entry.Length;
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                skipped.Add($"{entry.FullName}（{ex.Message}）");
            }
        }

        return new RimeBackupReport(restored, bytes, skipped, safetyPath);
    }

    private static IEnumerable<string> EnumerateUserFiles(string userRoot)
    {
        var options = new EnumerationOptions { RecurseSubdirectories = true, IgnoreInaccessible = true };
        var buildDir = Path.Combine(userRoot, ExcludedDirName);
        foreach (var file in Directory.EnumerateFiles(userRoot, "*", options))
        {
            if (file.StartsWith(buildDir + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
                continue;
            yield return file;
        }
    }

    /// <summary>Zip entry names use '/' so archives stay portable across OSes.</summary>
    private static string RelativeName(string userRoot, string file)
        => Path.GetRelativePath(userRoot, file).Replace('\\', '/');

    /// <summary>
    /// Resolves an entry name against the target root, rejecting anything that
    /// escapes it (zip slip) or is not a legal path on this platform.
    /// </summary>
    private static string? SafeResolve(string root, string entryName)
    {
        if (string.IsNullOrWhiteSpace(entryName)) return null;
        try
        {
            // GetFullPath absorbs ".." segments; an absolute or rooted entry
            // either lands inside the root or is rejected by the prefix check.
            var candidate = Path.GetFullPath(Path.Combine(root, entryName));
            var comparison = OperatingSystem.IsWindows()
                ? StringComparison.OrdinalIgnoreCase
                : StringComparison.Ordinal;
            return candidate.StartsWith(root + Path.DirectorySeparatorChar, comparison) ? candidate : null;
        }
        catch (Exception ex) when (ex is ArgumentException or NotSupportedException)
        {
            return null;
        }
    }

    private static bool DirectoryHasFiles(string dir)
        => Directory.EnumerateFiles(dir, "*", new EnumerationOptions
        {
            RecurseSubdirectories = true,
            IgnoreInaccessible = true,
        }).Any();

    private static string SafetyBackupZipPath(string zipPath)
        => Path.Combine(Path.GetDirectoryName(Path.GetFullPath(zipPath))!,
            $"pre-restore-{DateTime.Now:yyyyMMdd-HHmmss}.zip");
}
